def mark_of(c: dict) -> str:
    """The four states a criterion can be in, as one cell.

    Stages that carry ``void`` and ``diagnostic`` flags were writing them into
    the record and this table was ignoring both, so A3-5 appeared as **FAIL**
    when it is a criterion that **could not be evaluated**, and A3-2 and A3-3
    appeared as verdicts when they are diagnostics demoted in `a3_asset_channel`
    §5.1. Those are three different things and a reader of this file was seeing
    two. Stages that carry no flags are unaffected, so nothing else moves.
    """
    if c.get("diagnostic"):
        return "DIAG"
    if c.get("void"):
        return "VOID"
    return "PASS" if c["passed"] else "**FAIL**"


def _cell(text: str) -> str:
    """A pipe inside a table cell ends the cell, so every cell escapes its own.

    **Both columns, because for a long time only one did.** `detail` was escaped
    and `name` was not, for no reason either side records, and the asymmetry sat
    unexercised until a criterion was named `|λ| does not scale with the tick`
    and split its own row into five cells. **A guard applied to one of two
    identical inputs is a guard nobody has tested on the other.**
    """
    return text.replace("|", r"\|")


def criteria_table(criteria: list[dict]) -> list[str]:
    lines = ["| | criterion | detail |", "|---|---|---|"]
    for c in criteria:
        # Rendered rather than raised. A stage that forgets its detail strings
        # should show a visible gap in this table, not take the whole CI run
        # down with a KeyError before anything else is checked.
        detail = _cell(c.get("detail", "_no detail recorded_"))
        lines.append(f"| {mark_of(c)} | {_cell(c['name'])} | {detail} |")
    return lines


def render_block(criteria: list[dict], derived: dict, params: dict) -> list[str]:
    # Live criteria only, which is the count the stages print themselves. A
    # denominator that includes the voids and the diagnostics reports a stage
    # as having failed things it never decided.
    live = [c for c in criteria if not (c.get("void") or c.get("diagnostic"))]
    n_pass = sum(c["passed"] for c in live)
    n_void = sum(bool(c.get("void")) for c in criteria)
    n_diag = sum(bool(c.get("diagnostic")) for c in criteria)
    extra = "".join(
        f", {n} {label}"
        for n, label in ((n_void, "void"), (n_diag, "diagnostic"))
        if n
    )
    lines = [f"**{n_pass}/{len(live)} live criteria passed{extra}**", ""]
    lines += criteria_table(criteria)
    if derived:
        lines += ["", "Derived quantities:", ""]
        lines += [f"- `{k}` = {v:.4f}" for k, v in derived.items()]
    if params:
        lines += ["", "<details><summary>Parameters</summary>", "", "```json"]
        lines += [json.dumps(params, indent=2), "```", "", "</details>"]
    return lines


def subtitle(record: dict) -> str:
    """The one line that says what this record was computed on.

    Simulation stages are identified by rounds and seed; the empirical stages have
    neither and are identified by the sample and the settings that were applied to
    it. Reading these off the record rather than assuming a fixed set of keys is
    what lets a new stage be added without editing this function again.
    """
    # A6 runs several horizons in one record and replicates over a set of
    # seeds rather than one, so the generic line below would print a single
    # round count and `seed=?`, both of which would be wrong rather than merely
    # thin. Its own lengths are named instead.
    if record.get("stage", "").startswith("A6"):
        bits = [f"{record['seeds']} seeds", f"`rounds={record['rounds']}`"]
        for key, label in (
            ("long_rounds", "long run"),
            ("horizon", "horizon"),
        ):
            if record.get(key):
                bits.append(f"`{label.replace(' ', '_')}={record[key]}`")
        if "long_horizon" in record and record["long_horizon"]:
            bits.append(
                f"`horizon={record['long_horizon']['rounds']}`, "
                f"one cell carrying a registered multiple"
            )
        return " ".join(bits)

    if "rounds" in record:
        # A stage that replicates over a set of seeds records `seeds` and has
        # no single `seed`, and printing `seed=?` for it says the seed is
        # unknown when what is true is that there are five of them. A3 and A3c
        # are both in that shape and both were printing the question mark.
        if "seeds" in record:
            return f"`rounds={record['rounds']}` `{record['seeds']} seeds`"
        return f"`rounds={record['rounds']}` `seed={record.get('seed', '?')}`"

    # B6-A is identified by its publication-day domain rather than by a sample
    # size, because the estimator's domain is the registered object there: the
    # publisher's schedule changes inside the window and the calendar-day view
    # would carry a stale quote on two days in seven for the first eleven weeks
    # (`b6_cuba_prereg.md` §3.2).
    if record.get("stage") == "B6-A":
        start, end = record["window"]
        return (
            f"{record['publication_days']:,} publication days, {start} to {end}, "
            f"`segment_channel={record['segment_channel']}`"
        )

    # B14 is identified by the two windows and the venue-symbol counts, because
    # neither a round count nor a loan count exists for it and the generic
    # branch below would print "no sample metadata recorded" for a record that
    # carries both numbers.
    if record.get("stage") == "B13":
        return (
            f"{record['states_gate']:,} states over {record['products']} "
            f"products and {record['channels']} channels, one ten-minute window "
            f"of {record['capture_day']}, from the vendor's free public sample"
        )

    if record.get("stage") == "B14":
        start, end = record["window"]
        tail = f"{start} to {end}, October 2016 dropped as the pilot's phase-in month"
        # B14 has more than one record and they do not all carry the venue
        # counts. The gate does; the order-type robustness record does not, and
        # keying on the stage while indexing a field only one of them has is how
        # this function died the first time it met the second record.
        by = record.get("symbols_by_venue")
        if not by:
            return tail
        venues = ", ".join(f"{k} {v:,}" for k, v in sorted(by.items()))
        return f"{sum(by.values()):,} venue-symbols ({venues}), {tail}"

    bits = []
    for key in ("min_cell_size", "spread_bound", "registered_min_gap", "shapes_drawn"):
        if key in record:
            bits.append(f"`{key}={record[key]}`")
    for key, label in (
        ("excluded_implausible", "rows outside the plausibility band"),
        ("common_tract_years", "tract-years common to all programmes"),
    ):
        if key in record:
            bits.append(f"{record[key]:,} {label}")
    loans = record.get("variance", {}).get("n_loans") or record.get("n_loans")
    if loans:
        bits.insert(0, f"{loans:,} loans")
    # A record that names its own design at the top level rather than under
    # `variance` was printing "no sample metadata recorded" while carrying both
    # numbers. Read the top level too, for the same reason this function reads
    # keys off the record instead of switching on the stage name.
    if record.get("n_cells") and record.get("n_classes"):
        bits.append(f"{record['n_cells']:,} cells x {record['n_classes']} classes")
    real = record.get("theorem_3_on_real_data")
    if real:
        bits.insert(
            0,
            f"{real['cells_checked']:,} cells enumerated over "
            f"{real['loans_in_checked_cells']:,} loans",
        )
    elif record.get("national", {}).get("periods"):
        per = record["national"]["periods"]
        bits.insert(0, f"{len(per)} quarters, {per[0]} to {per[-1]}")
    elif record.get("shapes"):
        bits.insert(0, f"{len(record['shapes'])} graph shapes")
    return " ".join(bits) if bits else "_no sample metadata recorded_"


def derived_for(record: dict) -> dict[str, float]:
    """Headline numbers for the empirical stages, surfaced above the table.

    The simulation stages carry a ``derived`` block already. The empirical ones do
    not, because their headline quantities live at different depths of the record,
    so they are lifted here rather than duplicated into the JSON.
    """
    stage = record.get("stage")
    if stage == "B7" and record.get("step") == "crossfold":
        # B7-16 carries no criteria by design, so without this the
        # stage renders as a heading and nothing else. The arm surfaced is the
        # one the reading rests on, plus the control that reads zero.
        arms = record.get("arms", {})
        main = arms.get("drop_thinnest_2_balanced")
        ctrl = arms.get("all_%d" % record.get("n_classes", 19))
        if not main:
            return {}
        l1 = main["eigenvalues"][0]
        out = {
            "lambda1_17class_balanced": l1,
            "off_diagonal_share_of_lambda1": main["off_diag_part_of_lambda1"] / l1,
            "z_lambda1": main["z"],
            "z_lambda2": main.get("lambda2_z", float("nan")),
            "z_ordering_tau": main["tau_z"],
            "z_corr_v1_class_profile": main["corr_z"][2],
            "z_corr_v1_profile_slope": main["corr_z"][3],
            "profile_slope_separability": main["profile_slope_separability"],
            "naive_lambda1_same_sample": record["naive_eigenvalues"][0],
        }
        if ctrl:
            out["z_ordering_tau_19class_control"] = ctrl["tau_z"]
        return out
    if stage == "B7" and record.get("step") == "crossfold_depth":
        shares = [r["usable_share"] for r in record.get("classes", [])]
        if not shares:
            return {}
        return {"min_usable_share": min(shares), "max_usable_share": max(shares),
                "median_usable_share": sorted(shares)[len(shares) // 2]}
    if stage == "B1":
        real = record.get("theorem_3_on_real_data")
        if not real:
            return {}
        return {
            "half_mean_squared_holonomy": real["aggregate_half_mean_squared_holonomy"],
            "within_cell_variance": real["aggregate_within_cell_variance"],
            "worst_relative_error_per_cell": real["worst_relative_error_per_cell"],
        }
    if stage == "B2A":
        out = {
            "within_share_all_cells": record["variance"]["within_share"],
            "within_share_restricted": record["variance_restricted"]["within_share"],
            "bound_sweep_range": record["bound_sweep_range"],
        }
        ranked = record.get("rank_decomposition") or {}
        if ranked:
            out["within_share_ranked_nothing_excluded"] = ranked["within_share"]
        return out
    if stage == "B2B":
        nat = record.get("national", {})
        bounds = nat.get("bounds") or []
        if not bounds:
            return {}
        return {
            "latest_variance_lower_bound": bounds[-1],
            "smallest_across_quarters": min(bounds),
            "loop_a_within_cell_variance": record["loop_a_within_cell_variance"],
        }
    if stage == "B2A-placebo":
        overall = record["overall"]
        return {
            "conventional": overall["conventional"]["within_share"],
            "fha": overall["fha"]["within_share"],
            "va": overall["va"]["within_share"],
            "gap_conventional_minus_va": (
                overall["conventional"]["within_share"] - overall["va"]["within_share"]
            ),
            "split_half_null_largest_gap": record["split_half_null"]["max_abs_gap"],
        }
    return {}


def render_stage(record: dict, sub: str | None = None) -> str:
    """One record. ``sub`` demotes it to a subsection under a shared heading.

    A stage with several registered records used to emit its ``##`` heading once
    per record, which reads as several stages that happen to share a name. Stage
    B7 has eight and that is what made it worth fixing.

    ``sub`` is the record's **filename stem**, which is unique by construction
    and is the one string a reader needs in order to open the record. A prettier
    label would have to be derived from fields that two records of the same stage
    can share: both B7 gates carry ``step: "gate"`` and differ only in ``grid``,
    and both class-noise records carry ``step: "class_noise"``.
    """
    stage = record["stage"]
    depth = "###" if sub else "##"
    lines = [
        f"{depth} {sub if sub else STAGE_TITLES.get(stage, stage)}",
        "",
        subtitle(record),
        "",
    ]

    if "criteria" in record:
        lines += render_block(
            record["criteria"],
            record.get("derived", derived_for(record)),
            record.get("parameters", {}),
        )
    else:
        # One block per calibration preset. Both are reported: a finding that
        # holds under only one of them is a finding about that preset.
        nested = False
        for key, block in record.items():
            if not isinstance(block, dict) or "criteria" not in block:
                continue
            nested = True
            lines += [f"{'#' * (len(depth) + 1)} "
                      f"{PRESET_TITLES.get(key, key)}", ""]
            lines += render_block(
                block["criteria"],
                {
                    k: v
                    for k, v in block.items()
                    if isinstance(v, (int, float)) and not isinstance(v, bool)
                },
                {},
            )
            lines.append("")
        if not nested:
            # A record that gates nothing still has headline numbers, and a
            # heading with a subtitle and nothing under it is the shape a reader
            # takes as "this stage produced no numbers". B7-16 writes no criteria
            # **on purpose** (a criterion is structural or it is a
            # printed number with a reading declared in advance), so the file
            # that renders criteria had no way to show it at all.
            derived = record.get("derived", derived_for(record))
            if derived:
                lines += ["Derived quantities:", ""]
                lines += [f"- `{k}` = {v:.4f}" for k, v in derived.items()]
                lines.append("")

    return "\n".join(lines) + "\n"


#: Filename markers the experiments already use when they refuse to write over
#: a registered result. ``a3_asset_channel.py`` prints "writing beside the
#: registered result, not over it" and lands the run under one of these.
NOT_REGISTERED = (".offparam", ".smoke")


def is_registered(path: Path) -> bool:
    """Was this record produced at the stage's registered parameters?

    Read off the filename, because that is the signal the writers already use.
    An off-parameter or smoke record is **not a claim**: it was written beside
    the registered result precisely so it would not overwrite it, and rendering
    it into `RESULTS.md` under the identical heading undoes that. The committed
    file had `## A3` three times, at three hundred, forty and a hundred and
    twenty rounds, distinguished only by a line a reader would have to already
    know how to read.

    Worse than ambiguous, they go stale invisibly. Nothing regenerates them:
    `run_all.py` does not run them and CI does not either, so they are frozen
    snapshots of whatever the code was on the day somebody measured a cost, and
    they sit under the same heading as the current numbers.
    """
    return not any(m in path.name for m in NOT_REGISTERED)


def is_diagnostic(record: dict) -> bool:
    """Did the writer declare this record a diagnostic rather than a stage?

    Keyed on the record's own ``diagnostic_only`` field, which
    ``a3_asset_channel.py --retention-profile`` already writes and which says in
    plain text that it registers nothing and feeds no criterion. Such a file
    must not become a heading in `RESULTS.md`: `main` globs the whole directory,
    so running that diagnostic would otherwise add three empty stages to a file
    CI byte-diffs.

    **The first version of this test asked whether the record carried criteria,
    and that was wrong.** Four real stages carry none. The two B5 source audits
    carry none *by design*, and `STAGE_TITLES` says so twelve lines above: their
    verdict travels in the title precisely because they are audits rather than
    pre-registered criteria. `a3b_construction` and `b3_cip_slice` were dropped
    with them. A stage is not defined by having criteria, and the writer is the
    only thing that knows whether a record is a claim.
    """
    return bool(record.get("diagnostic_only"))


def is_record(record) -> bool:
    """Is this a stage record at all, or something else that landed in
    `results/`?

    **The third filter, extracted 2026-08-18 so that it stops being invisible.**
    `main` applied it inline while `tests/test_runner_covers_every_record.py`
    reimplemented the other two and not this one, so the guard demanded a runner
    job for `b9_datasets.json` while this file refused to render it. That test's
    own docstring says reimplementing the filter would let the two drift and
    that a guard which drifts from the thing it guards is `centrality_bins`
    with a different name. **It then reimplemented the filter.** The repair is
    the one that docstring asks for: one predicate, both callers.
    """
    return isinstance(record, dict) and "stage" in record


def main() -> int:
    records = sorted(RESULTS.glob("*.json"))
    if not records:
        print(f"no records found in {RESULTS}")
        return 1

    parts = [HEADER]
    off: list[str] = []
    bare: list[str] = []
    # A third list, added 2026-08-16. `results/` had held only stage records, and
    # `render_stage` reads `record["stage"]` directly while the grouping below
    # already tolerated its absence with a fallback key: an inconsistency that sat
    # there until something exercised it. `b9_datasets.json` did, a dataset
    # catalogue with venue codes at the top level and no `stage` anywhere, and the
    # renderer died on a `KeyError` naming nothing.
    #
    # **Skipped and named, not skipped quietly**, for the reason the two lists
    # above are printed: a file this script silently ignores is a file nobody
    # knows is being ignored. **Whether a non-record belongs in `results/` at all
    # is a question for whoever put it there**, and this list is how they find out
    # it is here.
    notrecord: list[str] = []
    # Grouped by stage so a stage with several registered records gets one
    # heading and one subsection per record, instead of its heading repeated.
    # ``records`` is sorted and dicts keep insertion order, so a stage sits at
    # the position of its first record and the output is a pure function of the
    # filenames, which is what the `git diff --exit-code` check needs.
    groups: dict[str, list[tuple[str, dict]]] = {}
    for path in records:
        if not is_registered(path):
            off.append(path.name)
            continue
        record = json.loads(path.read_text(encoding="utf-8"))
        if not is_record(record):
            notrecord.append(path.name)
            continue
        if is_diagnostic(record):
            bare.append(path.name)
            continue
        groups.setdefault(record.get("stage", path.stem), []).append(
            (path.stem, record)
        )

    for stage, items in groups.items():
        if len(items) == 1:
            parts.append(render_stage(items[0][1]))
            continue
        parts.append(f"## {STAGE_TITLES.get(stage, stage)}\n")
        for stem, record in items:
            parts.append(render_stage(record, sub=stem))

    # Encoding is pinned on both ends. Without it Path.read_text/write_text use
    # the platform's preferred encoding, so the same records render to different
    # bytes on Windows (cp936) and on the Linux runner, and the CI step that
    # diffs this file against the committed copy fails on content that is
    # identical. The titles below contain em dashes, so this is not hypothetical.
    OUT.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} from "
          f"{len(records) - len(off) - len(bare)} record(s) "
          f"in {len(groups)} stage(s)")
    # Announced rather than silent, for the reason `run_all.py` announces a
    # skipped stage: a renderer that quietly drops a file is indistinguishable
    # from one that never saw it.
    for names, why in (
        (off, "off-parameter or smoke runs, kept on disk and not rendered"),
        (bare, "declared diagnostic by the writer, so not stages"),
        (notrecord, "**no `stage` key, so not a record this file can render**; whoever wrote it into `results/` decides whether it belongs there"),
    ):
        if names:
            print(f"  {why}: {', '.join(names)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
