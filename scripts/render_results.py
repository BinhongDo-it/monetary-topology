"""Regenerate RESULTS.md from the JSON records in ``results/``.

RESULTS.md is generated rather than hand-written for one reason: a hand-written
results file drifts toward recording only what worked. Generating it from the
run records makes every failed criterion appear whether or not anyone wants it
there.

Usage::

    python scripts/render_results.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
OUT = ROOT / "RESULTS.md"

HEADER = """# Results

Generated by `scripts/render_results.py` from the JSON records in `results/`.
Do not edit by hand: edits are overwritten on the next run.

Failed criteria are listed alongside passing ones. A results file that records
only successes is the same kind of object as a statistic designed to look good,
and this project's own argument is about that kind of object.

**No generation date here on purpose.** This file is regenerated in CI and then
compared against the committed copy with ``git diff --exit-code``. Git already
records when a file was committed and by whom, and a "last generated" line would
guarantee that check fails on every day after the commit day, on content that is
character-for-character identical.
"""

