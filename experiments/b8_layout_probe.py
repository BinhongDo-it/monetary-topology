#!/usr/bin/env python3
"""B8 check C0: is the column layout the same in every quarterly file?

Registered in the B8 inputs register. C0 runs before the seven checks
of §3 and gates all of them: the files carry **no header row**, so every field is
taken by position, and a quarter whose column count differs from the others would
be read silently and wrongly. That is category error five, accounting location,
in its file-format form.

Usage::

    python experiments/b8_layout_probe.py
    python experiments/b8_layout_probe.py --rows 5000
    python experiments/b8_layout_probe.py --verify     # full CRC per archive, slow

Reads the archives **without extracting them**. Three reasons, and the third is
the one that matters:

* no second copy on disk, so there is nothing for a later cleanup to delete
  (the project's engineering rule 5);
* fewer bytes move off disk, so streaming the compressed member is faster than
  reading an inflated CSV would be;
* **a zip carries a CRC per member, a bare CSV does not.** ``--verify`` turns that
  into the truncation check the project's engineering rule 6 requires. A raw CSV can only be
  checked by reading it and hoping the tail looks plausible.

Writes ``results/b8_layout_probe.md``. Deterministic: archives sorted by name,
no wall-clock, no absolute paths, floats through an explicit format spec.
"""

from __future__ import annotations

import argparse
import sys
import zipfile
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "Fannie"
OUT = ROOT / "results" / "b8_layout_probe.md"

#: Fannie publishes these pipe-delimited. The probe does not assume it; it tries
#: each and reports which one yields a stable, plausible field count.
DELIMITERS = {"pipe": b"|", "comma": b",", "tab": b"\t", "semicolon": b";"}

#: Below this a delimiter is judged not to be the real one. The layout has ~100
#: fields, so anything in single digits is a coincidence of the data.
MIN_PLAUSIBLE_FIELDS = 20


def probe_member(fh, delimiter: bytes, max_rows: int) -> Counter:
    """Field counts over the first ``max_rows`` physical lines."""
    counts: Counter = Counter()
    for i, line in enumerate(fh):
        if i >= max_rows:
            break
        line = line.rstrip(b"\r\n")
        if not line:
            continue
        counts[line.count(delimiter) + 1] += 1
    return counts


def probe_archive(path: Path, max_rows: int, verify: bool) -> dict:
    rec: dict = {"archive": path.name, "bytes_compressed": path.stat().st_size}
    with zipfile.ZipFile(path) as zf:
        names = sorted(zf.namelist())
        rec["members"] = names
        if verify:
            bad = zf.testzip()
            rec["crc"] = "ok" if bad is None else f"FAILED at {bad}"
        if len(names) != 1:
            rec["error"] = f"expected one member, found {len(names)}"
            return rec
        info = zf.getinfo(names[0])
        rec["bytes_uncompressed"] = info.file_size
        rec["ratio"] = info.file_size / max(1, info.compress_size)

        best_name, best_counts = None, Counter()
        for dname, dbyte in sorted(DELIMITERS.items()):
            with zf.open(names[0]) as fh:
                counts = probe_member(fh, dbyte, max_rows)
            if not counts:
                continue
            modal = counts.most_common(1)[0][0]
            if modal >= MIN_PLAUSIBLE_FIELDS and modal > (
                best_counts.most_common(1)[0][0] if best_counts else 0
            ):
                best_name, best_counts = dname, counts

        rec["delimiter"] = best_name or "none plausible"
        rec["field_counts"] = dict(sorted(best_counts.items()))
        rec["modal_fields"] = best_counts.most_common(1)[0][0] if best_counts else 0
        rec["rows_seen"] = sum(best_counts.values())

        with zf.open(names[0]) as fh:
            first = fh.readline().rstrip(b"\r\n")
        rec["first_line_head"] = first[:200].decode("latin-1")
    return rec


def render(records: list[dict], max_rows: int, verify: bool) -> str:
    L: list[str] = []
    L.append("# B8 C0: quarterly layout probe\n")
    L.append(
        "Generated by `experiments/b8_layout_probe.py`. "
        "Registered in the B8 inputs register.\n"
    )
    L.append(f"Rows inspected per archive: {max_rows}. "
             f"CRC verification: {'on' if verify else 'off'}.\n")

    L.append("\n## Per archive\n")
    L.append("| archive | member | MB compressed | MB uncompressed | ratio | "
             "delimiter | modal fields | rows seen | field counts |")
    L.append("|---|---|---|---|---|---|---|---|---|")
    for r in records:
        if "error" in r:
            L.append(f"| {r['archive']} | {r['members']} | | | | | | | "
                     f"**{r['error']}** |")
            continue
        fc = ", ".join(f"{k}:{v}" for k, v in r["field_counts"].items())
        L.append(
            f"| {r['archive']} | {r['members'][0]} "
            f"| {r['bytes_compressed'] / 1e6:.1f} "
            f"| {r['bytes_uncompressed'] / 1e6:.1f} "
            f"| {r['ratio']:.2f} "
            f"| {r['delimiter']} | {r['modal_fields']} | {r['rows_seen']} | {fc} |"
        )

    if verify:
        L.append("\n## CRC\n")
        for r in records:
            L.append(f"- {r['archive']}: {r.get('crc', 'not run')}")

    L.append("\n## Verdict\n")
    ok = [r for r in records if "error" not in r and r["modal_fields"]]
    modes = sorted({r["modal_fields"] for r in ok})
    ragged = [r["archive"] for r in ok if len(r["field_counts"]) > 1]
    delims = sorted({r["delimiter"] for r in ok})

    if len(records) != len(ok):
        L.append("- **C0 FAILS.** At least one archive did not yield a readable "
                 "single member. Nothing downstream may be run.")
    elif len(modes) != 1:
        L.append(f"- **C0 FAILS.** Field count differs across quarters: {modes}. "
                 "Taking fields by position would read different columns in "
                 "different years, silently. Reconcile against the layout "
                 "document before any of §3's seven checks.")
    elif len(delims) != 1:
        L.append(f"- **C0 FAILS.** Delimiter differs across quarters: {delims}.")
    else:
        L.append(f"- **C0 passes on field count**: every quarter reads "
                 f"{modes[0]} fields, delimiter `{delims[0]}`.")
        L.append("- **Still to do by hand**: confirm that {0} matches the field "
                 "count in the CRT file layout and glossary, and that field 42 "
                 "(Modification Flag), 106 (Alternative Delinquency Resolution), "
                 "9, 12, 18, 40, 44, 63, 64 sit where the layout says they do. "
                 "**A matching count is not a matching order.**".format(modes[0]))
    if ragged:
        L.append(f"- **Ragged rows** in {', '.join(ragged)}: more than one field "
                 "count seen. Minority counts are usually a trailing blank line "
                 "or an embedded delimiter. Identify which before proceeding.")

    L.append("\n## What this probe does not decide\n")
    L.append("- It does not check that any field is **populated**. That is §3's "
             "C1 and C6.")
    L.append("- It does not count events. That is C4 and C5, and conclusion 28 "
             "says those come before any estimator.")
    L.append("- It does not establish the modification-programme question of "
             "§2, which is read from the layout document and not from the data.")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rows", type=int, default=1000)
    ap.add_argument("--verify", action="store_true",
                    help="full CRC per archive; minutes, not seconds")
    args = ap.parse_args()

    if not RAW.is_dir():
        print(f"missing directory: data/raw/Fannie", file=sys.stderr)
        return 2
    archives = sorted(RAW.glob("*.zip"))
    if not archives:
        print("no .zip found in data/raw/Fannie", file=sys.stderr)
        return 2

    records = [probe_archive(p, args.rows, args.verify) for p in archives]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(records, args.rows, args.verify),
                   encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    for r in records:
        print(f"  {r['archive']}: {r.get('modal_fields', '?')} fields, "
              f"delimiter {r.get('delimiter', '?')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
