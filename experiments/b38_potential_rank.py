"""B38: the rank of the obstruction to a scalar price potential, on cities by items.

Treat price as a field with two indices, `P(item i, city c)`. If a scalar
potential existed -- one price level per city -- then

    log P(i,c) = a_i + m_c

which is rank one in logs, and every square

    log P(i,c) - log P(j,c) - log P(i,c') + log P(j,c')

is exactly zero. That is the premise of Theorem 1, and it is what every spatial
price index and every purchasing-power construction assumes without stating.

**What is measured here is the rank of the obstruction, not its existence.**
That relative prices differ across cities is a common explanation, held by this
framework and by ordinary trade economics alike. Nobody computes the rank,
because only this framework says the rank is the surviving information.

**Currency does not enter.** Converting a city's prices multiplies its column by
a constant, which adds a constant in logs, which the city effect `m_c` absorbs
exactly. So this runs on every city at once with no exchange rate anywhere.

**The counting law and the two-way decomposition agree exactly.** On the complete
bipartite graph, `b1 = E - V + 1 = I*C - I - C + 1 = (I-1)(C-1)`, which is the
number of free parameters left in the residual after the row and column effects
are removed. The residual matrix *is* the representative of the class; that is
an identity, not an analogy, and B38-1 checks it elementwise.

**The floor is measured, not assumed.** The carrier's own noise was measured at
sd 0.0293 in logs against an administratively priced item, in
`results/b30_5_carrier_check.json`. A square is four prices, so under
independent noise its sd is twice that. For the spectrum, a matrix of pure noise
at that sd has its singular values bounded by about `sigma*(sqrt(n)+sqrt(m))`,
and B38-2 checks that this code returns nothing above that on synthetic rank-one
data.

Pre-registered design: the criteria are written in this file and in the record
this run produces, and every quantity it computes is reported. No threshold is
registered on any singular value; the spectrum is printed with both floors
beside it.

**Two floors, and both are reported.** The measured one uses the carrier noise
from arm A, which was measured on twelve large Chinese cities where the source
has many contributors; the archive reaches far thinner cities, so that number is
likely an underestimate and the count it gives is an upper bound on the rank.
The second floor needs no measurement at all: treat the *entire* residual as if
it were noise. That is the most conservative floor available, it cannot be
argued down, and whatever clears it is structure by any account.

Run:
    python experiments\\b38_potential_rank.py
"""

import csv
import json
import math
import sys
from pathlib import Path

import numpy as np

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

ROOT = Path(__file__).resolve().parents[1]
MAP = ROOT / "data" / "b30_5" / "column_map.json"
CARRIER = ROOT / "results" / "b30_5_carrier_check.json"
OUT = ROOT / "results" / "b38_potential_rank.json"

SEED = 20260901


def value(raw):
    try:
        v = float(raw)
    except (TypeError, ValueError):
        return None
    return v if math.isfinite(v) and v > 0 else None


def two_way(M):
    """Rows, columns, residual. Written as an identity and checked as one."""
    a = M.mean(axis=1, keepdims=True)
    b = (M - a).mean(axis=0, keepdims=True)
    R = M - a - b
    return a, b, R


def noise_edge(sigma, n, m):
    return sigma * (math.sqrt(n) + math.sqrt(m))


def main():
    spec = json.loads(MAP.read_text(encoding="utf-8"))
    cols_all = [c for c, m in spec["mapping"].items() if m.get("agrees")]
    # A rate is not a price. The mortgage row is quoted in per cent, so a
    # city's price level does not multiply it, and it therefore sits in the
    # residual as a large direction by construction rather than by economics --
    # it led the first direction on the first run. The column-naming step
    # already flags it, in its own words, as the one item where no currency
    # enters. The station is run both ways and both are reported.
    cols_price = [c for c in cols_all
                  if "in %" not in spec["mapping"][c]["item"].lower()]
    src = ROOT / spec["source_file"]
    rows = list(csv.DictReader(src.open(encoding="utf-8-sig", newline="")))
    citycol, ctrycol = spec["city_column"], spec["country_column"]

    sigma = json.loads(CARRIER.read_text(encoding="utf-8")) \
        ["arm_a_administrative"]["panel_noise_sd"]

    print("=" * 78)
    print("B38: is the city-by-item log price field generated by one scalar")
    print("     per city, and if not, how many dimensions is the obstruction")
    print("=" * 78)
    print("  carrier   %s, %d cities" % (src.name, len(rows)))
    print("  items     %d, of which %d are prices; x37 is excluded because "
          "the source\n            redefined it between the two vintages"
          % (len(cols_all), len(cols_price)))
    print("  noise     sd %.4f in logs, measured in arm A of the carrier check"
          % sigma)

    out_arms = {}
    for arm, cols in (("prices only", cols_price), ("with the rate row", cols_all)):
        print("\n" + "#" * 78)
        print("# arm: %s, %d items" % (arm, len(cols)))
        print("#" * 78)
        out_arms[arm] = run(rows, cols, spec, citycol, ctrycol, sigma)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"noise_sd": sigma, "arms": out_arms},
                              ensure_ascii=False, indent=1), encoding="utf-8")
    print("\nwritten: %s" % OUT)


def run(rows, cols, spec, citycol, ctrycol, sigma):
    items = [spec["mapping"][c]["item"] for c in cols]
    rng = np.random.default_rng(SEED)
    # --- the complete submatrix: no imputation anywhere ---
    full = [r for r in rows if all(value(r[c]) for c in cols)]
    M = np.log(np.array([[value(r[c]) for c in cols] for r in full],
                        dtype=float)).T          # items x cities
    names = [(r[citycol], r[ctrycol]) for r in full]
    I, C = M.shape
    print("\n  main arm: cities carrying every item, so the matrix is complete")
    print("    %d items x %d cities" % (I, C))
    b1 = I * C - (I + C) + 1
    print("    b1 = E - V + 1 = %d, and (I-1)(C-1) = %d"
          % (b1, (I - 1) * (C - 1)))
    if b1 != (I - 1) * (C - 1):
        raise SystemExit("the counting law and the residual dimension disagree.")

    a, b, R = two_way(M)
    recon = float(np.abs(M - (a + b + R)).max())
    print("\n  B38-1  the decomposition is an identity: max |M - (a+b+R)| = %.3e"
          % recon)
    print("         %s" % ("PASS" if recon < 1e-12 else "FAIL"))

    # --- B38-2, the known answer: rank one plus noise must return nothing ---
    synth = (a + b) + rng.normal(0.0, sigma, size=M.shape)
    _, _, Rs = two_way(synth)
    ss = np.linalg.svd(Rs, compute_uv=False)
    edge = noise_edge(sigma, I, C)
    above_s = int((ss > edge).sum())
    print("\n  B38-2  known answer: a rank-one field plus noise of the measured")
    print("         sd, run through this same code")
    print("         noise edge sigma*(sqrt(I)+sqrt(C)) = %.4f" % edge)
    print("         largest synthetic singular value    = %.4f" % ss[0])
    print("         directions above the edge           = %d   %s"
          % (above_s, "PASS" if above_s == 0 else "FAIL"))

    # --- B38-3, the residual itself ---
    sv = np.linalg.svd(R, compute_uv=False)
    sd_R = float(R.std())
    sq_sd = 2.0 * sigma
    print("\n  B38-3  the residual, printed and not judged")
    print("         sd(R) over all cells        %.4f" % sd_R)
    print("         one price's noise sd        %.4f" % sigma)
    print("         a square's noise sd (4 prices) %.4f" % sq_sd)
    print("         sd(R) is %.1f times one price's noise" % (sd_R / sigma))

    # squares: a random sample of them, printed as a distribution
    n_sq = 20000
    ii = rng.integers(0, I, n_sq); jj = rng.integers(0, I, n_sq)
    cc = rng.integers(0, C, n_sq); dd = rng.integers(0, C, n_sq)
    keep = (ii != jj) & (cc != dd)
    sq = (R[ii[keep], cc[keep]] - R[jj[keep], cc[keep]]
          - R[ii[keep], dd[keep]] + R[jj[keep], dd[keep]])
    q = np.percentile(np.abs(sq), [50, 90, 99])
    print("         |square sum|: median %.4f  p90 %.4f  p99 %.4f  (n=%d)"
          % (q[0], q[1], q[2], keep.sum()))
    print("         median square is %.1f times the noise a square carries"
          % (q[0] / sq_sd))

    # --- B38-4, the rank ---
    above = int((sv > edge).sum())
    # The floor that needs nothing measured: suppose every last part of the
    # residual is noise. Then its own sd is the noise sd, and this is the
    # highest floor any reading of this matrix could defend.
    edge_hi = noise_edge(sd_R, I, C)
    above_hi = int((sv > edge_hi).sum())
    tot = float((sv ** 2).sum())
    print("\n  B38-4  the spectrum of the residual, with both floors beside it")
    print("         measured floor      %.4f   (noise sd %.4f from arm A)"
          % (edge, sigma))
    print("         conservative floor  %.4f   (the whole residual taken as "
          "noise, sd %.4f)" % (edge_hi, sd_R))
    print("         %-4s %10s %9s %9s" % ("k", "sigma_k", "share", "cum"))
    cum = 0.0
    for k in range(min(15, len(sv))):
        cum += sv[k] ** 2 / tot
        mark = ("above both" if sv[k] > edge_hi else
                ("above the measured floor only" if sv[k] > edge else "below both"))
        print("         %-4d %10.4f %8.2f%% %8.2f%%   %s"
              % (k + 1, sv[k], 100 * sv[k] ** 2 / tot, 100 * cum, mark))
    print("         above the measured floor      %d of %d" % (above, len(sv)))
    print("         above the conservative floor  %d of %d" % (above_hi, len(sv)))
    print("         The truth is between them, and the second number is the one")
    print("         that cannot be argued down: it survives even if the whole")
    print("         residual is called measurement error.")

    # --- B38-5, print the objects, not the counts ---
    U, S, Vt = np.linalg.svd(R, full_matrices=False)
    print("\n  B38-5  what the surviving directions are. Items with the largest")
    print("         loading, printed rather than counted")
    for k in range(min(3, max(above_hi, 1))):
        u = U[:, k]
        idx = np.argsort(-np.abs(u))[:6]
        print("         direction %d (sigma %.3f):" % (k + 1, S[k]))
        for t in idx:
            print("            %+7.3f  %s" % (u[t], items[t].split(" :: ")[-1][:52]))
        v = Vt[k, :]
        ci = np.argsort(-np.abs(v))[:4]
        print("            cities at the ends: %s"
              % "; ".join("%s, %s (%+.3f)" % (names[t][0], names[t][1], v[t])
                          for t in ci))

    return {
        "items": I, "cities": C, "b1": b1,
        "noise_edge": edge, "conservative_edge": edge_hi,
        "b38_1_reconstruction_max_abs": recon,
        "b38_2_synthetic_above_edge": above_s,
        "b38_3_resid_sd": sd_R,
        "b38_3_square_abs_quantiles": {"p50": q[0], "p90": q[1], "p99": q[2]},
        "b38_4_singular_values": [float(x) for x in sv[:40]],
        "b38_4_above_measured_edge": above,
        "b38_4_above_conservative_edge": above_hi,
        "b38_5_top_items": [
            {"direction": k + 1, "sigma": float(S[k]),
             "items": [{"item": items[t], "loading": float(U[t, k])}
                       for t in np.argsort(-np.abs(U[:, k]))[:6]]}
            for k in range(min(3, max(above_hi, 1)))],
    }


if __name__ == "__main__":
    main()
