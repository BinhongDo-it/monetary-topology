#!/usr/bin/env python3
"""B8-3 under the second curve construction. O36's disposition.

**Why B8-3 needed this and did not get it the first time.** O33 waved B8-3
through on one sentence: its `delta/floor` is 1.07e5 to 4.18e6 while the curve
spread is 10 to 1,010, so two to four orders of margin. **That sentence used a
mislabelled denominator.** `b8_cmt_sensitivity.FLOOR` holds 6.47e-06 to
6.71e-05, which is §6.2.11.4's `(i-b) median absolute` column -- the residual
of the clean-cure loops after the closed form was subtracted, which that same
table measures at **172 to 2,343 times the floor**. Against the matched-window
floor the curve spread is **1,773 to 358,532**, the same order as B8-3's own
`delta/floor`, and the margin argument is void.

**B8-3 is the headline** (§15.7 moved it there from B8-1 before the run), and
it is the one criterion this session never re-ran under an alternative
construction. It is re-run here.

**The argument that survives, and it is not a magnitude argument.** A curve
change shifts every loop's `omega`. B8-3's statistic is a *difference* between
two path populations inside the same cell, and both populations sit in the same
window with similar `d - i` gaps, so a common shift cancels in the delta. That
is a claim about differencing, not about orders of magnitude, **and it has
never been measured.** This file measures it.

**No logic is duplicated.** `b8_3_paths.analyse` takes a `data=` dict, so the
alternative arm goes through the same cells, the same stratified delta and the
same permutation null. Only `sig.omega`, `sig.measurable`, `floor.omega` are
rebuilt; nothing else in the cache is a function of the curve.

Usage:

    python experiments/b8_3_curve.py run
    python experiments/b8_3_curve.py run --only 2019Q1
    python experiments/b8_3_curve.py selftest
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

import b8_core as K                                            # noqa: E402
import b8_loops as L                                           # noqa: E402
import b8_loop_omega as Z8                                     # noqa: E402
import b8_cache as C                                           # noqa: E402
import b8_3_paths as P3                                        # noqa: E402
import b8_2_curve as CV                                        # noqa: E402

OUT = K.ROOT / "results" / "b8_3_curve.md"

RULE_A, RULE_B, ROUND_BOUND = CV.RULE_A, CV.RULE_B, CV.ROUND_BOUND


def rebuilt(name: str, d: dict, cache_root=None, src=None) -> dict:
    """`d` with both arms' `omega` recomputed under `RULE_B`.

    **Everything not listed here is rule-independent and is passed through**:
    `t_A`/`t_M`/`t_B`/`arm` come from `find_loops`, which reads delinquency
    status and fields 42, 63 and 108; `n1`/`n3`/`window`/`rem_A` are derived
    from those; `closed` is `loop_residual_ideal(B0, i, P, k)` and carries no
    discount rate; `ideal` is a balance-path flag. Rebuilding them would only
    create a way for the two arms to differ for a reason that is not the curve.
    """
    sig_b = CV.under_rule(name, RULE_B, d["sig"], cache_root=cache_root,
                          src=src)
    om_fb, meas_fb = CV.floor_under(name, RULE_B, d["floor"],
                                    cache_root=cache_root, src=src)
    sig = dict(d["sig"])
    sig["omega"] = np.asarray(sig_b["omega"], float)
    sig["measurable"] = np.asarray(sig_b["measurable"], bool)
    flo = dict(d["floor"])
    flo["omega"] = om_fb
    flo["measurable"] = meas_fb
    return {"sig": sig, "floor": flo, "meta": d.get("meta", {})}


def compare(name: str, cache_root=None, pos=None, tab=None, core_root=None,
            n_perm: int = P3.N_PERM, src=None) -> dict:
    root = core_root or cache_root
    d = C.get(name, pos=pos, tab=tab, core_root=root)
    a = P3.analyse(name, n_perm=n_perm, data=d, core_root=root)
    b = P3.analyse(name, n_perm=n_perm, data=rebuilt(name, d, cache_root=root,
                                                     src=src), core_root=root)
    return {"name": name, "A": a, "B": b}


def _p(perm) -> float:
    """The permutation `p`, wherever `b8_3_paths` keeps it. Read by name and
    not by position, so a change in that dict surfaces as a NaN here rather
    than as a plausible number."""
    if isinstance(perm, dict):
        for k_ in ("p", "p_value", "pval"):
            if k_ in perm:
                return float(perm[k_])
    return float("nan")


def _r(x, k=4):
    return "nan" if not np.isfinite(x) else f"{x:+.{k}e}"


def render(rows: list[dict]) -> str:
    Ls: list[str] = []
    A_ = Ls.append
    A_("# B8-3 under the second curve construction (O36)\n")
    A_("Generated by `experiments/b8_3_curve.py`.\n")
    A_("**B8-3 is the headline** (§15.7) and it is the one criterion that was "
      "never re-run under an alternative construction. O33 exempted it on the "
      "ground that its `delta/floor` was two to four orders above the curve "
      "spread. **O36 found that comparison used a mislabelled denominator**: "
      "`b8_cmt_sensitivity.FLOOR` holds the `(i-b)` residual, which "
      "§6.2.11.4 itself measures at 172 to 2,343 times the floor. Against the "
      "matched-window floor the curve spread is 1,773 to 358,532, **the same "
      "order as `delta/floor`**, so the exemption is void and this is the "
      "measurement that replaces it.\n")
    A_(f"Registered **`{RULE_A[0]}` / `{RULE_A[1]}`** against the far corner "
      f"**`{RULE_B[0]}` / `{RULE_B[1]}`**, both choices changed at once.\n")
    A_("**The argument being tested is about differencing, not magnitude.** A "
      "curve change shifts every loop; B8-3's statistic is a difference "
      "between two path populations inside one cell, and a shift common to "
      "both cancels. That was asserted and is now measured.\n")
    if not rows:
        return "\n".join(Ls) + "\n_no data_\n"

    A_("\n## 1. The headline statistic under both\n")
    A_("| archive | floor A | floor B | **delta A** | **delta B** | "
      "`delta/floor` A | `delta/floor` B | B/A |")
    A_("|---|---|---|---|---|---|---|---|")
    for r in rows:
        a, b = r["A"], r["B"]
        da, db = a["existence"]["delta"], b["existence"]["delta"]
        qa = abs(da) / a["floor"] if a["floor"] > 0 else float("nan")
        qb = abs(db) / b["floor"] if b["floor"] > 0 else float("nan")
        A_(f"| {r['name']} | {a['floor']:.4e} | {b['floor']:.4e} | "
           f"**{_r(da)}** | **{_r(db)}** | {qa:,.0f} | {qb:,.0f} | "
           f"{(qb / qa if qa > 0 else float('nan')):.4f} |")

    A_("\n## 2. Does the delta keep its sign, and the null\n")
    A_("**§19's criterion is existence, not magnitude**: two realisable paths "
      "to the same terminal state carry different accumulated `omega`. So the "
      "question a construction can answer is whether the sign and the "
      "rejection survive, not whether the number is identical.\n")
    A_("| archive | sign A | sign B | **sign flips** | perm `p` A | perm `p` B "
      "| cells + A | cells - A | cells + B | cells - B |")
    A_("|---|---|---|---|---|---|---|---|---|---|")
    flips = 0
    for r in rows:
        a, b = r["A"], r["B"]
        sa, sb = np.sign(a["existence"]["delta"]), np.sign(b["existence"]["delta"])
        fl = np.isfinite(sa) and np.isfinite(sb) and sa != sb
        flips += bool(fl)
        A_(f"| {r['name']} | {sa:+.0f} | {sb:+.0f} | "
           f"**{'YES' if fl else 'no'}** | {_p(a['perm']):.3f} | "
           f"{_p(b['perm']):.3f} | {a['strat']['pos']} | "
           f"{a['strat']['neg']} | {b['strat']['pos']} | "
           f"{b['strat']['neg']} |")

    A_("\n## 3. The verdict\n")
    ok = [r for r in rows
          if np.isfinite(r["B"]["existence"]["delta"])
          and np.sign(r["B"]["existence"]["delta"])
          == np.sign(r["A"]["existence"]["delta"])
          and _p(r["B"]["perm"]) < 0.05]
    A_("| archives | sign survives **and** `p` < 0.05 under B | sign flips | "
      "**reading** |")
    A_("|---|---|---|---|")
    good = len(ok) == len(rows) and flips == 0
    A_(f"| {len(rows)} | {len(ok)} | {flips} | "
       + ("**B8-3 survives the curve construction.** The headline holds under "
          "both, the delta keeps its sign on every archive and the "
          "permutation still rejects. **O33's exemption is replaced by a "
          "measurement**, and O36's correction to the margin argument does "
          "not reach the finding" if good
          else "**B8-3 is construction-dependent.** The registered reading is "
               "not retracted and the alternative is not adopted; both are "
               "reported. **This is the headline, so it is the whole "
               "stage's disposition and it goes to the top of the ledger**")
       + " |")

    A_("\n## What this does not decide\n")
    A_("- **Which construction is right.** §16.11 pinned one before the run.")
    A_("- **O36's naming defect.** Renaming the three floors is separate and "
      "changes no number.")
    A_("- Causality of any kind.\n")
    return "\n".join(Ls) + "\n"


def selftest() -> int:
    fails: list[str] = []
    root = K.CACHE / "_selftest_loops"
    zp = root / "raw" / f"2099Q1_{L._fixture_tag()}.zip"
    if not zp.exists():
        L._synth_loops(zp)
    cr = root / "cache"
    K.build_archive(zp, force=True, cache_root=cr)
    with K.Core(zp.stem, cols=CV.COLS, cache_root=cr) as c:
        months = np.unique(c.row["period"][:])
        months = months[months != K.U16_NA]
    curved = {(int(mi), lab): [1.0 + 3.0 * (ten / 240.0) ** 0.5]
              for mi in months.tolist()
              for lab, ten in (("1 Mo", 1), ("1 Yr", 12), ("5 Yr", 60),
                               ("10 Yr", 120), ("20 Yr", 240))}
    pos, tab = Z8.curve_table_from(curved, RULE_A)
    d = C.get(zp.stem, cache_root=cr, core_root=cr, pos=pos, tab=tab)

    # **`rebuilt` must replace exactly two arrays and pass the rest through.**
    # Everything it copies is rule-independent by construction, and copying
    # something that is not would let the two arms differ for a reason that is
    # not the curve, which is the whole comparison.
    rb = rebuilt(zp.stem, d, cache_root=cr, src=curved)
    for f_ in ("t_A", "t_M", "t_B", "arm", "n1", "n3", "window", "rem_A",
               "leg1", "leg2"):
        if not np.array_equal(np.asarray(d["sig"][f_]),
                              np.asarray(rb["sig"][f_]), equal_nan=True):
            fails.append(f"`rebuilt` changed `sig.{f_}`, which is not a "
                         "function of the curve")
    for f_ in ("t_A", "t_M", "t_B", "k", "closed", "ideal"):
        if not np.array_equal(np.asarray(d["floor"][f_]),
                              np.asarray(rb["floor"][f_]), equal_nan=True):
            fails.append(f"`rebuilt` changed `floor.{f_}`; `closed` in "
                         "particular carries no discount rate at all")
    # **and the four it is supposed to replace, against arithmetic done
    # outside `rebuilt`.** Three of them can look right by accident: the floor
    # is expected not to move, so copying the cached one through is invisible
    # unless the recomputation is checked directly.
    sb_x = CV.under_rule(zp.stem, RULE_B, d["sig"], cache_root=cr, src=curved)
    ob_x, mb_x = CV.floor_under(zp.stem, RULE_B, d["floor"], cache_root=cr,
                                src=curved)
    for got, want, nm in (
            (rb["sig"]["omega"], sb_x["omega"], "sig.omega"),
            (rb["sig"]["measurable"], sb_x["measurable"], "sig.measurable"),
            (rb["floor"]["omega"], ob_x, "floor.omega"),
            (rb["floor"]["measurable"], mb_x, "floor.measurable")):
        if not np.array_equal(np.asarray(got), np.asarray(want),
                              equal_nan=True):
            fails.append(f"`rebuilt`'s `{nm}` is not what the alternative "
                         "rule produces; it is being passed through from the "
                         "cache")
    # **`measurable` is not a curve-dependent field, and that is asserted.**
    # The two rules differ in the *value* at a horizon, never in whether one
    # exists: both interpolate below the first published tenor and both give a
    # finite number past the last, so a row is dropped only where its month is
    # missing, which is the same month for both. A mutation run confirmed
    # swapping it is a no-op. **If a real archive ever breaks this the two
    # arms stop being comparable**, so it is checked rather than assumed.
    if not np.array_equal(np.asarray(sb_x["measurable"]),
                          np.asarray(d["sig"]["measurable"])):
        fails.append("the two constructions disagree on which loops are "
                     "measurable. They were expected to differ only in value, "
                     "and if they differ in computability the two arms are "
                     "drawn on different populations")
    if np.array_equal(np.asarray(d["sig"]["omega"]),
                      np.asarray(rb["sig"]["omega"])):
        fails.append("`rebuilt` returned the cached `sig.omega` unchanged on "
                     "a curve the two rules disagree on, so the alternative "
                     "arm is the registered arm wearing a different name")
    # **the floor is expected NOT to move**, for the reason `floor_under`
    # gives: a clean cure re-contracts nothing, so `n_prev == n_now` and the
    # annuity cancels whatever the curve is. Only rounding may be left.
    fm = d["floor"]["measurable"].astype(bool) & d["floor"]["ideal"].astype(bool)
    if fm.any():
        sh = float(np.max(np.abs(np.asarray(rb["floor"]["omega"])
                                 - np.asarray(d["floor"]["omega"]))[fm]))
        if sh > ROUND_BOUND:
            fails.append(f"the floor arm moved by {sh:.3e} past "
                         f"{ROUND_BOUND:.3e}; the clean-cure cancellation is "
                         "not holding and B8-3's floor is construction-"
                         "dependent, which is a larger finding than B8-3")

    # -- `_p` reads the permutation `p` by name ----------------------------
    # **A `_p` that always returned zero would make every archive significant
    # under both constructions and the verdict would read "survives" whatever
    # the data did.**
    if abs(_p({"p": 0.037, "obs": 1.0, "n": 999}) - 0.037) > 1e-15:
        fails.append("`_p` did not read the `p` key")
    if not np.isnan(_p({"obs": 1.0, "n": 999})):
        fails.append("`_p` invented a number for a dict with no `p`; a "
                     "renamed key must surface as NaN, not as significance")
    if not np.isnan(_p(None)) or not np.isnan(_p(0.04)):
        fails.append("`_p` accepted something that is not the permutation "
                     "record")

    # **through `P3.analyse`, both arms.** The point of `data=` is that no
    # logic is duplicated, so the check is that the injected path reproduces
    # the cached path exactly when handed the cache back.
    a1 = P3.analyse(zp.stem, n_perm=19, data=d, core_root=cr)
    a2 = P3.analyse(zp.stem, cache_root=cr, core_root=cr, pos=pos, tab=tab,
                    n_perm=19)
    if not np.isclose(a1["floor"], a2["floor"], rtol=0, atol=0):
        fails.append("injecting the cache gave a different floor from reading "
                     "it, so `data=` is not the same code path")
    if a1["existence"]["delta"] != a2["existence"]["delta"] and not (
            np.isnan(a1["existence"]["delta"]) and np.isnan(a2["existence"]["delta"])):
        fails.append("injecting the cache gave a different delta from reading "
                     "it")
    cmp_ = compare(zp.stem, cache_root=cr, core_root=cr, pos=pos, tab=tab,
                   n_perm=19, src=curved)
    if cmp_["A"]["floor"] != a1["floor"]:
        fails.append("`compare`'s A arm is not the registered reading")

    txt = render([cmp_])
    for cmpl in K.check_markdown_tables(txt):
        fails.append(f"malformed table: {cmpl}")
    for need in ("## 1. The headline statistic under both",
                 "## 2. Does the delta keep its sign", "## 3. The verdict"):
        if need not in txt:
            fails.append(f"render omits `{need}`")
    if "_no data_" not in render([]):
        fails.append("the empty render did not say so")
    print(f"  fixture: floor {cmp_['A']['floor']:.3e} / "
          f"{cmp_['B']['floor']:.3e}, delta "
          f"{cmp_['A']['existence']['delta']:.3e} / "
          f"{cmp_['B']['existence']['delta']:.3e}", file=sys.stderr)

    for m in fails:
        print("FAIL " + m, file=sys.stderr)
    if fails:
        return 1
    print("selftest: ok, only the two curve-dependent arrays move and both "
          "arms share one code path", file=sys.stderr)
    return 0


def run(names: list[str]) -> int:
    pos, tab = Z8.curve_table()
    rows = []
    for n in names:
        print(f"reading {n}", file=sys.stderr)
        r = compare(n, pos=pos, tab=tab)
        rows.append(r)
        print(f"  done {n}: delta {r['A']['existence']['delta']:+.3e} -> "
              f"{r['B']['existence']['delta']:+.3e}", file=sys.stderr)
    txt = render(rows)
    bad = K.check_markdown_tables(txt)
    if bad:
        for b in bad:
            print("MALFORMED " + b, file=sys.stderr)
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(txt, encoding="utf-8")
    print(f"wrote {OUT}", file=sys.stderr)
    return 0


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("command", choices=["run", "selftest"])
    ap.add_argument("--only", action="append", default=None)
    args = ap.parse_args()
    if args.command == "selftest":
        raise SystemExit(selftest())
    root = K.CACHE / K.SCHEMA_VERSION
    names = sorted(p.name for p in root.iterdir()
                   if p.is_dir() and (p / "manifest.json").exists()) \
        if root.exists() else []
    if args.only:
        keep = set(args.only)
        names = [n for n in names if n in keep]
    if not names:
        print("no core table. Run: python experiments/b8_core.py build",
              file=sys.stderr)
        raise SystemExit(1)
    raise SystemExit(run(names))


if __name__ == "__main__":
    main()
