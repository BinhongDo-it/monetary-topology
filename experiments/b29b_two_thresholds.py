"""B29 chunk 2: connectivity and consistency are two different thresholds.

Ordinary percolation asks when a signal reaches everyone: that is H0 becoming
trivial, i.e. the graph becoming connected. This project needs something else,
that the values everyone holds agree, which is H1 of the complex generated by the
cycles agents can actually walk becoming trivial.

Prediction: p_connect < p_homology, with a wide phase between them in which a
price is universally known and globally inconsistent.

Model: G(n, p). Arbitrage horizon L, so the fillable 2-cells are the cycles of
length at most L. gap = b1(G) - rank(span of those cycles) = dim H1.

Seeds: 5. Enough, because the two curves are separated by a factor and the
seed-to-seed spread is reported alongside so the reader can see it is small
relative to the separation. No reason to run 20.
"""
import numpy as np, itertools, json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from b29_locality import short_cycles

CACHE = os.path.join(os.path.dirname(__file__), "..", "results", "b29b_two_thresholds.json")


def er_graph(n, p, rng):
    E = [(i, j, 0) for i in range(n) for j in range(i + 1, n) if rng.random() < p]
    return E


def components(n, E):
    par = list(range(n))
    def find(x):
        while par[x] != x:
            par[x] = par[par[x]]; x = par[x]
        return x
    for i, j, _ in E:
        a, b = find(i), find(j)
        if a != b: par[a] = b
    return len({find(i) for i in range(n)})


def measure(n, p, L, seed):
    rng = np.random.default_rng(seed)
    E = er_graph(n, p, rng)
    if not E:
        return dict(connected=False, b1=0, gap=0, edges=0)
    C = components(n, E)
    b1 = len(E) - n + C
    cyc = short_cycles(n, E, L)
    rank = int(np.linalg.matrix_rank(cyc)) if cyc.shape[0] else 0
    return dict(connected=(C == 1), b1=int(b1), gap=int(b1 - rank), edges=len(E))


def sweep(n=40, L=3, ps=None, seeds=(0, 1, 2, 3, 4)):
    ps = ps or [0.04,0.06,0.08,0.10,0.12,0.15,0.20,0.25,0.30,0.35,0.40,0.50,0.60,0.70]
    rows = []
    for p in ps:
        res = [measure(n, p, L, s) for s in seeds]
        gaps = [r["gap"] for r in res]
        rows.append(dict(p=p, L=L,
                         connected_frac=sum(r["connected"] for r in res) / len(res),
                         gap_mean=float(np.mean(gaps)), gap_min=int(min(gaps)),
                         gap_max=int(max(gaps)),
                         b1_mean=float(np.mean([r["b1"] for r in res]))))
    return rows


def main():
    cache = json.load(open(CACHE)) if os.path.exists(CACHE) else {}
    for L in (3, 4):
        key = f"n40-L{L}"
        if key not in cache:
            cache[key] = sweep(n=40, L=L)
        print(f"n = 40, arbitrage horizon L = {L}, 5 seeds")
        print(f"  {'p':>5} {'connected':>10} {'b1 mean':>8} {'gap mean':>9} "
              f"{'gap min':>8} {'gap max':>8}")
        for r in cache[key]:
            print(f"  {r['p']:>5.2f} {r['connected_frac']:>10.1f} {r['b1_mean']:>8.1f} "
                  f"{r['gap_mean']:>9.1f} {r['gap_min']:>8d} {r['gap_max']:>8d}")
        print()
    os.makedirs(os.path.dirname(CACHE), exist_ok=True)
    json.dump(cache, open(CACHE, "w"), indent=1, sort_keys=True)


if __name__ == "__main__":
    main()
